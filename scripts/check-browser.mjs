  assert.equal(blog.posts.read('first').body, 'Agent changed this file');
  await page.locator('#extension-editor-agent-context').click();
  const copied = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()));
  assert.equal(copied.unsavedChanges, true); assert.match(copied.draft.body, /Human unsaved text/);
  checks.push('Real CLI edit conflicts are rejected; editor text remains available in agent context');
  page.once('dialog', dialog => dialog.accept());
  await page.locator('[data-slug="second"]').click();
  await page.waitForFunction(() => document.querySelector('#title').value === 'Second Article');
  await page.locator('.cm-content').click(); await page.keyboard.press('Control+z');
