import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {loadSite, serve} from '../packages/core/index.mjs';

const require = createRequire(import.meta.url);
const {chromium} = require(process.env.AGENT_BLOG_PLAYWRIGHT_MODULE || 'playwright');
const root = fileURLToPath(new URL('../', import.meta.url));
const artifacts = path.join(root, 'test-results');
fs.mkdirSync(artifacts, {recursive: true});
const screenshots = path.resolve(process.env.AGENT_BLOG_SCREENSHOT_DIR || artifacts);
fs.mkdirSync(screenshots, {recursive: true});
const fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-blog-browser-'));
fs.mkdirSync(path.join(fixture, 'content'));
const plugins = ['markdown', 'highlight', 'math', 'editor', 'theme-paper'].map(name => path.join(root, 'packages', name, 'index.mjs'));
plugins.push(path.join(root, 'examples/demo/plugins/writing-tools.mjs'));
fs.writeFileSync(path.join(fixture, 'blog.json'), JSON.stringify({version: 1, title: 'Browser Test', plugins}));
const blog = await loadSite(fixture);
const body = '# Browser check\n\n$E=mc^2$\n\n$$\nx^2 + y^2 = z^2\n$$\n\n```javascript\nconst answer = 42;\n```';
blog.posts.write('first', {metadata: {title: 'Browser Article', date: '2026-10-14T12:00:00Z', draft: true, extra: {keep: true}}, body}, null);
blog.posts.write('second', {metadata: {title: 'Second Article', date: '2026-10-13', draft: true}, body: 'Second unique body'}, null);
const server = await serve(blog, {port: 0});
const origin = 'http://127.0.0.1:' + server.address().port;
const demoBlog = await loadSite(path.join(root, 'examples/demo'));
const demoServer = await serve(demoBlog, {port: 0});
const demo = 'http://127.0.0.1:' + demoServer.address().port;
const terminalBlog = await loadSite(demoBlog.site.root, {config: {...demoBlog.site, plugins: demoBlog.site.plugins.map(entry => entry === '@agent-blog/theme-paper' ? '@agent-blog/theme-terminal' : entry)}});
const terminalServer = await serve(terminalBlog, {port: 0});
const terminal = 'http://127.0.0.1:' + terminalServer.address().port;
const checks = [], errors = [];
let browser;
try {
  browser = await chromium.launch({executablePath: process.env.AGENT_BLOG_CHROME || undefined, args: ['--no-sandbox']});
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}, permissions: ['clipboard-read', 'clipboard-write']});
  await context.route('**/*', route => [origin, demo, terminal].includes(new URL(route.request().url()).origin) ? route.continue() : route.abort());
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin + '/__editor/');
  await page.locator('.cm-content').waitFor();
  await page.frameLocator('#preview').locator('.katex').first().waitFor();
  assert.ok(await page.locator('.cm-content span').count() > 3);
  assert.ok(await page.frameLocator('#preview').locator('.hljs-keyword').count() > 0);
  checks.push('Markdown source highlighting, fenced code highlighting, inline and display math preview');
  await page.locator('#extension-writing-tools-stats').click();
  await page.waitForFunction(() => document.querySelector('#writing-tools-panel').textContent.includes('Agent 命令返回'));
  await page.locator('#writing-tools-series').fill('Plugin series');
  await page.locator('#extension-writing-tools-quote').click();
  assert.match(await page.locator('.cm-content').textContent(), />/);
  checks.push('A plugin adds toolbar actions, a panel and metadata fields; its action calls the same agent command');
  await page.locator('#title').fill('Human changed the title');
  await page.locator('#save-post').click();
  await page.waitForFunction(() => document.querySelector('#save-status').textContent === '草稿已保存');
  const saved = blog.posts.read('first');
  assert.equal(saved.metadata.title, 'Human changed the title');
  assert.deepEqual(saved.metadata.extra, {keep: true});
  assert.equal(saved.metadata.date, '2026-10-14T12:00:00Z');
  assert.equal(saved.metadata.series, 'Plugin series');
  checks.push('Browser editing uses the same source file and preserves custom metadata and timestamps');
  const agent = spawnSync(process.execPath, [path.join(root, 'packages/core/cli.mjs'), 'put', 'first', '--site', fixture, '--stdin', '--if-revision', saved.revision, '--json'], {encoding: 'utf8', input: JSON.stringify({metadata: saved.metadata, body: 'Agent changed this file'})});
  assert.equal(agent.status, 0, agent.stderr);
  await page.locator('.cm-content').click();
  await page.keyboard.press('Control+End');
  await page.keyboard.insertText('\nHuman unsaved text');
  await page.locator('#save-post').click();
  await page.waitForFunction(() => document.querySelector('#save-status').textContent.includes('文件已被 Agent'));
  assert.match(await page.locator('.cm-content').textContent(), /Human unsaved text/);
  assert.equal(blog.posts.read('first').body, 'Agent changed this file');
  await page.locator('#agent-context').click();
  const copied = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()));
  assert.equal(copied.unsavedChanges, true); assert.match(copied.draft.body, /Human unsaved text/);
  checks.push('Real CLI edit conflicts are rejected; editor text remains available in agent context');
  page.once('dialog', dialog => dialog.accept());
  await page.locator('[data-slug="second"]').click();
  await page.waitForFunction(() => document.querySelector('#title').value === 'Second Article');
  await page.locator('.cm-content').click(); await page.keyboard.press('Control+z');
  assert.equal((await page.locator('.cm-content').textContent()).trim(), 'Second unique body');
  checks.push('Undo history does not cross article boundaries');
  await page.locator('[data-slug="first"]').click();
  await page.waitForFunction(() => document.querySelector('.cm-content').textContent.includes('Agent changed this file'));
  await page.locator('#title').fill('Submitted title');
  let delayed = false;
  await page.route('**/__editor/api/posts/first', async route => {
    if (route.request().method() !== 'PUT') return route.continue();
    const response = await route.fetch(); delayed = true;
    await new Promise(resolve => setTimeout(resolve, 400));
    await route.fulfill({response});
  });
  await page.locator('#save-post').click();
  while (!delayed) await new Promise(resolve => setTimeout(resolve, 20));
  await page.locator('#title').fill('New typing while saving');
  await page.locator('#writing-tools-series').fill('New series while saving');
  await page.waitForFunction(() => document.querySelector('#save-status').textContent.includes('新的修改尚未保存'));
  assert.equal(blog.posts.read('first').metadata.title, 'Submitted title');
  assert.equal(await page.locator('#title').inputValue(), 'New typing while saving');
  assert.equal(blog.posts.read('first').metadata.series, 'Plugin series');
  await page.locator('#agent-context').click();
  const inFlight = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()));
  assert.equal(inFlight.draft.metadata.series, 'New series while saving');
  assert.equal(inFlight.unsavedChanges, true);
  await page.unroute('**/__editor/api/posts/first');
  await page.locator('#save-post').click();
  await page.waitForFunction(() => document.querySelector('#save-status').textContent === '草稿已保存');
  assert.equal(blog.posts.read('first').metadata.series, 'New series while saving');
  checks.push('Typing during a pending save is retained and remains explicitly unsaved');
  const desktop = await context.newPage(); desktop.on('pageerror', error => errors.push(error.message));
  await desktop.goto(demo + '/__editor/');
  await desktop.frameLocator('#preview').locator('.prose').waitFor();
  await desktop.screenshot({path: path.join(screenshots, 'editor-desktop.png')});
  await desktop.goto(demo + '/');
  assert.equal(await desktop.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgb(248, 242, 232)');
  await desktop.screenshot({path: path.join(screenshots, 'blog-desktop.png'), fullPage: true});
  await desktop.screenshot({path: path.join(screenshots, 'theme-paper.png'), fullPage: true});
  const titles = await desktop.locator('.post-row h2').allTextContents();
  await desktop.goto(terminal + '/');
  assert.equal(await desktop.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgb(17, 26, 24)');
  assert.deepEqual(await desktop.locator('.post-row h2').allTextContents(), titles);
  await desktop.screenshot({path: path.join(screenshots, 'theme-terminal.png'), fullPage: true});
  checks.push('Paper and terminal skins render the same articles with independent styles');
  const mobile = await context.newPage(); mobile.on('pageerror', error => errors.push(error.message));
  await mobile.setViewportSize({width: 390, height: 844});
  await mobile.goto(demo + '/__editor/'); await mobile.locator('.cm-content').waitFor();
  await mobile.frameLocator('#preview').locator('.prose').waitFor();
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await mobile.screenshot({path: path.join(screenshots, 'editor-mobile.png'), fullPage: true});
  checks.push('Desktop and mobile editing layouts render without page overflow');
  assert.deepEqual(errors, []);
  const report = {checkedAt: new Date().toISOString(), browser: await browser.version(), checks, pageErrors: errors, productionRequests: false};
  fs.writeFileSync(path.join(artifacts, 'browser-verification.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} finally {
  if (browser) await browser.close();
  await Promise.all([server, demoServer, terminalServer].map(value => new Promise(resolve => value.close(resolve))));
  fs.rmSync(fixture, {recursive: true, force: true});
}
