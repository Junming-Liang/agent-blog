import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
import {randomBytes} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {loadSite, serve, build} from '../packages/core/index.mjs';

const require = createRequire(import.meta.url), {chromium} = require(process.env.AGENT_BLOG_PLAYWRIGHT_MODULE || 'playwright');
const root = fileURLToPath(new URL('../', import.meta.url)), fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-blog-auth-browser-'));
const artifacts = path.join(root, 'test-results');
fs.mkdirSync(artifacts, {recursive: true});
fs.mkdirSync(path.join(fixture, 'content'));
const plugins = ['editor', 'editor-agent', 'editor-markdown', 'editor-highlight', 'markdown', 'theme-overwatch', 'auth'].map(name => path.join(root, 'packages', name, 'index.mjs'));
fs.writeFileSync(path.join(fixture, 'blog.json'), JSON.stringify({version: 1, title: 'Independent writing space', plugins}));
const blog = await loadSite(fixture);
const published = blog.posts.write('public', {metadata: {title: 'Public article', draft: false}, body: 'Public content'}, null);
blog.posts.write('draft', {metadata: {title: 'Private draft', draft: true, extra: {keep: true}}, body: 'Private original'}, null);
const link = await blog.execute('auth-setup'), server = await serve(blog, {port: 0}), origin = 'http://127.0.0.1:' + server.address().port;
const secret = randomBytes(24).toString('base64url') + ' test passphrase';
const browser = await chromium.launch({executablePath: process.env.AGENT_BLOG_CHROME || undefined, args: ['--no-sandbox']});
const report = {at: new Date().toISOString(), checks: [], pageErrors: [], externalRequests: [], wordpressRequests: []};
try {
  const context = await browser.newContext({viewport: {width: 390, height: 844}});
  await context.route('**/*', route => {
    const url = new URL(route.request().url());
    if (url.origin !== origin) { report.externalRequests.push(url.origin); return route.abort(); }
    if (/wp-login|wp-admin|\.php(?:$|\?)/.test(url.pathname)) report.wordpressRequests.push(url.pathname);
    return route.continue();
  });
  const page = await context.newPage();
  page.on('pageerror', error => report.pageErrors.push(error.message));
  assert.equal((await context.request.get(origin + '/__editor/api/posts')).status(), 401);
  await page.goto(origin + link.url);
  await page.locator('#token-field[hidden]').waitFor({state: 'attached'});
  assert.equal(new URL(page.url()).hash, '');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({path: path.join(artifacts, 'independent-auth-setup-mobile.png')});
  await page.locator('[name="username"]').fill('test-owner');
  await page.locator('[name="password"]').fill(secret);
  await page.locator('form button').click();
  await page.waitForURL(origin + '/__editor/');
  await page.locator('.cm-content').waitFor();
  const cookie = (await context.cookies()).find(value => value.name === 'agent_blog_session');
  assert.ok(cookie.httpOnly && cookie.sameSite === 'Strict');
  report.checks.push('One-time browser setup removes its fragment and creates a private independent session');
  await page.locator('.post-item[data-slug="draft"]').click();
  await page.locator('#title').fill('Saved through independent login');
  await page.locator('.cm-content').click();
  await page.keyboard.press('ControlOrMeta+A');
  await page.keyboard.insertText('Edited independently from WordPress.');
  await page.locator('#save-post').click();
  await page.waitForFunction(() => document.querySelector('#save-status').textContent === '草稿已保存');
  assert.equal(blog.posts.read('draft').body, 'Edited independently from WordPress.');
  assert.deepEqual(blog.posts.read('draft').metadata.extra, {keep: true});
  assert.equal(blog.posts.read('public').revision, published.revision);
  await page.frameLocator('#preview').locator('.brand').waitFor();
  report.checks.push('Authenticated browser editing and theme preview retain custom metadata and unrelated content');
  await page.locator('#extension-auth-logout').click();
  await page.waitForURL(origin + '/__auth/login');
  assert.equal((await context.request.get(origin + '/__editor/api/posts')).status(), 401);
  assert.equal((await context.request.get(origin + '/_assets/editor/bundle/editor.js')).status(), 401);
  assert.equal((await context.request.get(origin + '/posts/draft/')).status(), 404);
  assert.equal((await context.request.get(origin + '/posts/public/')).status(), 200);
  await page.screenshot({path: path.join(artifacts, 'independent-auth-login-mobile.png')});
  await page.locator('[name="username"]').fill('test-owner');
  await page.locator('[name="password"]').fill('incorrect');
  await page.locator('form button').click();
  await page.waitForFunction(() => document.querySelector('#message').textContent.includes('用户名或密码不正确'));
  await page.locator('[name="password"]').fill(secret);
  await page.locator('form button').click();
  await page.waitForURL(origin + '/__editor/');
  await page.locator('.cm-content').waitFor();
  report.checks.push('Logout revokes access, invalid credentials fail and independent sign-in restores editing');
  await build(blog);
  assert.ok(!fs.existsSync(path.join(fixture, 'dist/.auth')));
  assert.ok(!fs.existsSync(path.join(fixture, 'dist/_assets/editor')));
  assert.deepEqual(report.pageErrors, []);
  assert.deepEqual(report.externalRequests, []);
  assert.deepEqual(report.wordpressRequests, []);
  report.passed = true;
} finally {
  await browser.close();
  await new Promise(resolve => server.close(resolve));
  fs.rmSync(fixture, {recursive: true, force: true});
  fs.writeFileSync(path.join(artifacts, 'independent-auth-browser.json'), JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify(report));
}
